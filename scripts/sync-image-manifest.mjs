import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "assets", "image-manifest.json");
const outputPath = path.join(root, "src", "generated", "image-assets.js");
const folders = {
  fish: "fish",
  bugs: "bug",
  fossils: "fossil",
  art: "art",
  items: "item",
  residents: "resident",
  npcs: "npc",
  gyroids: "gyroid",
  facilities: "facility"
};
const supported = new Set([".webp", ".png", ".jpg", ".jpeg", ".avif"]);
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.entries)) {
  throw new Error("assets/image-manifest.json must use schemaVersion 1 and an entries array");
}
const manifestIds = new Set();
for (const entry of manifest.entries) {
  if (manifestIds.has(entry.id)) throw new Error(`duplicate manifest image id: ${entry.id}`);
  manifestIds.add(entry.id);
}
const explicitById = new Map(manifest.entries.map((entry) => [entry.id, entry]));
const assets = {};

for (const [folder, prefix] of Object.entries(folders)) {
  const entries = await readdir(path.join(root, "assets", folder), { withFileTypes: true });
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (!entry.isFile() || !supported.has(path.extname(entry.name).toLowerCase())) continue;
    const id = path.basename(entry.name, path.extname(entry.name));
    if (!new RegExp(`^${prefix}-[a-z0-9-]+$`).test(id)) {
      throw new Error(`${folder}/${entry.name}: filename must start with ${prefix}- and use a stable slug`);
    }
    if (assets[id]) throw new Error(`duplicate image id: ${id}`);
    const explicit = explicitById.get(id) ?? {};
    assets[id] = {
      localPath: `./assets/${folder}/${entry.name}`,
      alt: explicit.alt ?? "",
      sourceType: explicit.sourceType ?? "user_supplied_local",
      notes: explicit.notes ?? "ローカル画像フォルダから自動登録。"
    };
  }
}

for (const entry of manifest.entries) {
  if (!assets[entry.id]) throw new Error(`manifest entry has no matching local file: ${entry.id}`);
}

const generated = `// Generated by scripts/sync-image-manifest.mjs. Do not add remote URLs here.\nexport const imageAssetMap = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
await writeFile(outputPath, generated, "utf8");
console.log(JSON.stringify({ imageAssets: Object.keys(assets).length, output: "src/generated/image-assets.js" }, null, 2));
